export function getAccessoryLabel(
  code: StandardAccessoryCode,
  lang: Language,
  customName?: string
): string {
  if (code === 'custom') return customName || '';
  const found = STANDARD_ACCESSORIES.find((a) => a.code === code);
  return found ? found.labels[lang] : customName || code;
}

